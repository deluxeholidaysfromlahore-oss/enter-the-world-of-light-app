// Helper query functions
export const getAudioItemById = (id: string): AudioLibraryItem | undefined => {
  return MASTER_AUDIO_LIBRARY_ITEMS.find((item) => item.id === id);
};

export const getItemsByAudioType = (typeId: AudioTypeId): AudioLibraryItem[] => {
  return MASTER_AUDIO_LIBRARY_ITEMS.filter((item) => item.audioTypeId === typeId);
};

export const getItemsByCategory = (categoryId: string): AudioLibraryItem[] => {
  if (categoryId === 'all') return MASTER_AUDIO_LIBRARY_ITEMS;
  return MASTER_AUDIO_LIBRARY_ITEMS.filter((item) => item.categoryId === categoryId);
};

// Comprehensive audit helper for testing and reporting
export const getMasterAuditReport = () => {
  const totalTopics = MASTER_AUDIO_LIBRARY_ITEMS.length;
  const categoriesCount = ALL_13_CATEGORIES.length;
  const typeATopics = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.audioTypeId === 'TYPE_A_DUA_AZKAR');
  const typeBTopics = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.audioTypeId === 'TYPE_B_NASHEED_SONGS');
  const availableAudio = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.audioStatus === 'available');
  const pendingAudio = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.audioStatus === 'pending');
  const verifiedContent = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.verificationStatus === 'verified');
  const publicDomain = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.licensingStatus === 'public-domain');
  const openSource = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.licensingStatus === 'open-source-cc');
  const permissionGranted = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.licensingStatus === 'permission-granted');

  const categoryBreakdown = ALL_13_CATEGORIES.map((cat) => {
    const items = MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.categoryId === cat.id);
    return {
      categoryNumber: cat.categoryNumber,
      categoryId: cat.id,
      label: cat.label,
      totalCount: items.length,
      availableAudioCount: items.filter((i) => i.audioStatus === 'available').length,
      pendingAudioCount: items.filter((i) => i.audioStatus === 'pending').length,
    };
  });

  return {
    totalTopics,
    categoriesCount,
    typeACount: typeATopics.length,
    typeBCount: typeBTopics.length,
    availableAudioCount: availableAudio.length,
    pendingAudioCount: pendingAudio.length,
    verifiedContentCount: verifiedContent.length,
    licensingBreakdown: {
      publicDomainCount: publicDomain.length,
      openSourceCount: openSource.length,
      permissionGrantedCount: permissionGranted.length,
      needsReviewCount: MASTER_AUDIO_LIBRARY_ITEMS.filter((i) => i.licensingStatus === 'needs-review').length,
    },
    categoryBreakdown,
  };
};
